def test_sizes_come_from_the_machine_profile() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        machine = Path(tmp) / "machine.json"
        machine.write_text(json.dumps({
            "thumbnail_size": ["150x150"],
            "thumbnails": ["110x110/PNG", "380x380/COLPIC", "210x210/COLPIC"],
        }), encoding="utf-8")
        assert thumbnails.gcode_sizes(machine) == [(380, 380), (210, 210), (110, 110)]
        machine.write_text(json.dumps({"thumbnails": "48x48/PNG, 300x300/PNG, 300x300"}),
                           encoding="utf-8")
        assert thumbnails.gcode_sizes(machine) == [(300, 300), (48, 48)]
        machine.write_text(json.dumps({"thumbnail_size": ["272x272/PNG", "96x96/PNG"]}),
                           encoding="utf-8")
        assert thumbnails.gcode_sizes(machine) == [(272, 272), (96, 96)]
        machine.write_text("{}", encoding="utf-8")
        assert thumbnails.gcode_sizes(machine) == [(300, 300), (48, 48)]
    assert thumbnails.gcode_sizes(Path("/nowhere/machine.json")) == [(300, 300), (48, 48)]


