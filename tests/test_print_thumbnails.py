_RELS = (
    '<?xml version="1.0" encoding="UTF-8"?>\n<Relationships xmlns="http://schemas.openxmlformats'
    '.org/package/2006/relationships">\n <Relationship Target="/Metadata/plate_1.png" Id="rel-2" '
    'Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/thumbnail"/>\n'
    '<Relationship Target="/Metadata/plate_1_small.png" Id="rel-5" '
    'Type="http://schemas.bambulab.com/package/2021/cover-thumbnail-small"/>\n</Relationships>'
)
_MODEL_SETTINGS = (
    '<?xml version="1.0" encoding="UTF-8"?>\n<config>\n  <plate>\n'
    '    <metadata key="plater_id" value="1"/>\n'
    '    <metadata key="gcode_file" value="Metadata/plate_1.gcode"/>\n  </plate>\n</config>\n'
)


def _sliced_3mf(path: Path) -> Path:
    """The shape of a headless OrcaSlicer .gcode.3mf: rels name images the zip lacks."""
    with zipfile.ZipFile(str(path), "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml",
                         '<Default Extension="png" ContentType="image/png"/>')
        archive.writestr("Metadata/plate_1.gcode.md5",
                         hashlib.md5(_HEADER.encode()).hexdigest().upper())
        archive.writestr("Metadata/plate_1.gcode", _HEADER)
        archive.writestr("Metadata/model_settings.config", _MODEL_SETTINGS)
        archive.writestr("Metadata/slice_info.config", "<config/>")
        archive.writestr("_rels/.rels", _RELS)
    return path


def test_3mf_gets_plate_images_a_thumbnailed_gcode_and_a_matching_md5() -> None:
    block = thumbnails.gcode_block({(110, 110): _fake_png(110, 110)})
    with tempfile.TemporaryDirectory() as tmp:
        path = _sliced_3mf(Path(tmp) / "part.gcode.3mf")
        before = {name: zipfile.ZipFile(str(path)).read(name)
                  for name in ("[Content_Types].xml", "Metadata/slice_info.config", "_rels/.rels")}
        changed = thumbnails.inject_3mf(path, _fake_png(512, 512), _fake_png(128, 128), block)
        assert changed is True
        with zipfile.ZipFile(str(path)) as archive:
            assert archive.testzip() is None
            names = archive.namelist()
            assert names.count("Metadata/plate_1.gcode") == 1, names
            assert names.count("Metadata/plate_1.gcode.md5") == 1, names
            assert _png_size(archive.read(thumbnails.PLATE_PNG)) == (512, 512)
            assert _png_size(archive.read(thumbnails.PLATE_SMALL_PNG)) == (128, 128)
            assert archive.getinfo(thumbnails.PLATE_PNG).compress_type == zipfile.ZIP_STORED
            gcode = archive.read("Metadata/plate_1.gcode")
            assert b"; thumbnail begin 110x110 " in gcode
            md5 = archive.read("Metadata/plate_1.gcode.md5").decode("ascii")
            assert md5 == hashlib.md5(gcode).hexdigest().upper() and len(md5) == 32
            settings = archive.read("Metadata/model_settings.config").decode("utf-8")
            assert '<metadata key="thumbnail_file" value="Metadata/plate_1.png"/>' in settings
            for name, data in before.items():
                assert archive.read(name) == data, name
        # Idempotent: a 3MF that already has its plate image is not rebuilt.
        stamp = path.read_bytes()
        assert thumbnails.inject_3mf(path, b"x", b"y", block) is False
        assert path.read_bytes() == stamp


def test_a_thumbnail_failure_never_fails_the_slice() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        path = _sliced_3mf(Path(tmp) / "part.gcode.3mf")
        stamp = path.read_bytes()
        warnings = thumbnails.add_to_slice(Path(tmp) / "missing.stl", path, None, None)
        assert warnings and warnings[0].startswith("thumbnails skipped"), warnings
        assert path.read_bytes() == stamp


