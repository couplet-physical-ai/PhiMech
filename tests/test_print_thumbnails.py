def test_gcode_block_is_moonraker_readable_and_sits_after_the_header() -> None:
    images = {(110, 110): _fake_png(110, 110), (380, 380): _fake_png(380, 380) * 30}
    block = thumbnails.gcode_block(images)
    with tempfile.TemporaryDirectory() as tmp:
        gcode = Path(tmp) / "plate_1.gcode"
        gcode.write_text(_HEADER, encoding="ascii")
        assert thumbnails.inject_gcode_file(gcode, block) is True
        text = gcode.read_bytes()
        lines = text.decode("ascii").splitlines()
        assert lines.index("; HEADER_BLOCK_END") < lines.index("; THUMBNAIL_BLOCK_START")
        assert lines.index("; THUMBNAIL_BLOCK_END") < lines.index("; EXECUTABLE_BLOCK_START")
        assert all(len(line) <= 2 + thumbnails.LINE_CHARS for line in lines if
                   line.startswith("; ") and "thumbnail" not in line and "BLOCK" not in line)
        found = thumbnails.read_gcode_thumbnails(text)
        assert [(w, h) for w, h, _ in found] == [(380, 380), (110, 110)], "largest first"
        assert found[0][2] == images[(380, 380)] and found[1][2] == images[(110, 110)]
        # The original G-code is all still there, in order, after the block.
        assert text.decode("ascii").replace(block.decode("ascii"), "") == _HEADER
        # Idempotent: a G-code that already has a thumbnail is left alone.
        assert thumbnails.inject_gcode_file(gcode, block) is False
        assert gcode.read_bytes() == text


def test_a_length_mismatch_is_refused_like_moonraker_does() -> None:
    bad = b"; thumbnail begin 10x10 999\n; AAAA\n; thumbnail end\n"
    try:
        thumbnails.read_gcode_thumbnails(bad)
    except ValueError as exc:
        assert "999" in str(exc)
    else:
        raise AssertionError("a block whose base64 length disagrees with its header must fail")


