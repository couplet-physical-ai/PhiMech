"""Plate thumbnails for headless slices (phimech/print/thumbnails.py).

Headless OrcaSlicer cannot make a GL context, so every ``.gcode.3mf`` PhiMech produced had no
``Metadata/plate_1.png`` (although ``_rels/.rels`` points at it) and no ``; thumbnail begin``
block: the QIDI Max 4 screen and the Fluidd/Mainsail file lists showed a blank tile.

Runs both ways: ``python tests/test_print_thumbnails.py`` and pytest. The end-to-end test needs
OrcaSlicer, its Qidi profiles and OpenSCAD, and skips when any is missing; everything else uses
synthetic files.
"""
from __future__ import annotations

import hashlib
import json
import os as _os
import struct
import sys
import tempfile
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

try:
    import pytest
except ImportError:  # pragma: no cover - exercised by the system-python runner
    pytest = None  # type: ignore[assignment]

from phimech.csg import ops  # noqa: E402
from phimech.print import profiles, slicer, thumbnails  # noqa: E402

_PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
_HEADER = (
    "; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n; total layer number: 3\n"
    "; HEADER_BLOCK_END\n\n; external perimeters extrusion width = 0.42mm\n\n"
    "; EXECUTABLE_BLOCK_START\nG28\nG1 X10 Y10\n; EXECUTABLE_BLOCK_END\n"
)


class _Skipped(Exception):
    pass


def _skip(message: str) -> None:
    if pytest is not None and _os.environ.get("PYTEST_CURRENT_TEST"):
        pytest.skip(message)
    raise _Skipped(message)


def _png_size(data: bytes):
    assert data[:8] == _PNG_SIGNATURE, data[:8]
    return struct.unpack(">II", data[16:24])


def _fake_png(width: int, height: int) -> bytes:
    """Enough of a PNG for the injector, which never decodes it."""
    return _PNG_SIGNATURE + b"\x00\x00\x00\rIHDR" + struct.pack(">II", width, height) + bytes(97)


