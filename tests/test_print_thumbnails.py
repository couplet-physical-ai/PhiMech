def test_a_real_slice_carries_thumbnails_in_gcode_and_3mf() -> None:
    from phimech.backends.openscad import OpenSCADBackend

    if not slicer.available():
        _skip("orcaslicer is not installed")
    if profiles.profiles_root() is None:
        _skip("OrcaSlicer vendor profiles are not installed")
    if not OpenSCADBackend().available():
        _skip("openscad is not installed")
    with tempfile.TemporaryDirectory(prefix="phimech-test-thumb-") as tmp:
        stl = Path(tmp) / "cube.stl"
        OpenSCADBackend().render(ops.box(20, 20, 10), stl, "stl")
        result = slicer.slice_stl(stl, Path(tmp) / "out")
        # Only PhiMech's own thumbnail warnings: OrcaSlicer's "skipping thumbnail rendering"
        # line is the very reason this module exists and may appear in the slicer log.
        assert not [w for w in result.warnings if w.startswith("thumbnails ")], result.warnings
        wanted = thumbnails.gcode_sizes(Path(tmp) / "out" / "profiles" / "machine.json")
        assert result.gcode is not None
        with result.gcode.open("rb") as handle:
            found = thumbnails.read_gcode_thumbnails(handle.read(1024 * 1024))
        assert [(w, h) for w, h, _ in found] == wanted, (found, wanted)
        for width, height, png in found:
            assert _png_size(png) == (width, height)
        with zipfile.ZipFile(str(result.gcode_3mf)) as archive:
            assert _png_size(archive.read(thumbnails.PLATE_PNG)) == (512, 512)
            assert _png_size(archive.read(thumbnails.PLATE_SMALL_PNG)) == (128, 128)
            inner = archive.read("Metadata/plate_1.gcode")
            assert inner == result.gcode.read_bytes(), "bare and archived G-code must agree"
            assert archive.read("Metadata/plate_1.gcode.md5").decode() == (
                hashlib.md5(inner).hexdigest().upper())
        assert result.layer_count == 50, "metadata must still parse after injection"


def _run_direct() -> int:
    tests = [value for name, value in sorted(globals().items()) if name.startswith("test_")]
    failures = 0
    for test in tests:
        try:
            test()
        except _Skipped as exc:
            print("SKIP {}: {}".format(test.__name__, exc))
        except Exception as exc:  # pragma: no cover - only used by direct invocation
            failures += 1
            print("FAIL {}: {}".format(test.__name__, exc))
        else:
            print("PASS {}".format(test.__name__))
    return failures


if __name__ == "__main__":
    raise SystemExit(_run_direct())
