class _Skipped(Exception):
    pass


def _require_openscad() -> OpenSCADBackend:
    backend = OpenSCADBackend()
    if backend.available():
        return backend
    message = "openscad is not installed"
    # pytest.skip() raises Skipped, which derives from BaseException, so it sails through the
    # `except Exception` in _run_direct and turns a skip into a crash with a traceback and exit 1.
    # Delegating merely because pytest is IMPORTABLE was the bug: `bin/phimech check` runs each test
    # file directly with the venv python, where pytest is installed but is not driving. pytest sets
    # PYTEST_CURRENT_TEST for the duration of each test, so it tells "installed" from "running".
    if pytest is not None and _os.environ.get("PYTEST_CURRENT_TEST"):
        pytest.skip(message)
    raise _Skipped(message)


def test_emit_cube_exact() -> None:
    assert emit(Cube((10, 20, 30))) == (
        "// generated by phimech 0.1.0 — do not edit\n"
        "cube(size=[10, 20, 30], center=false);\n"
    )


def test_emit_cylinder_exact() -> None:
    assert emit(Cylinder(h=12.5, r=3, r2=2, center=True, segments=32)) == (
        "// generated by phimech 0.1.0 — do not edit\n"
        "cylinder(h=12.5, r1=3, r2=2, center=true, $fn=32);\n"
    )


def test_emit_polygon_and_transform_exact() -> None:
    node = Translate(
        (1, 2, 3),
        [
            Polygon(
                ((0, 0), (10, 0), (10, 5), (0, 5)),
                ((0, 1, 2, 3),),
            )
        ],
    )
    assert emit(node) == (
        "// generated by phimech 0.1.0 — do not edit\n"
        "translate([1, 2, 3]) {\n"
        "  polygon(points=[[0, 0], [10, 0], [10, 5], [0, 5]], paths=[[0, 1, 2, 3]]);\n"
        "}\n"
    )


def test_emit_all_node_types() -> None:
    nodes = [
        Cube(),
        Cylinder(),
        Sphere(),
        Polyhedron(((0, 0, 0), (1, 0, 0), (0, 1, 0)), ((0, 1, 2),)),
        Import("part.stl"),
        Square(),
        Circle(),
        Polygon(((0, 0), (1, 0), (0, 1))),
        LinearExtrude(2, [Square()]),
        RotateExtrude([Square()]),
        Union([Cube(), Sphere()]),
        Difference([Cube(), Sphere()]),
        Intersection([Cube(), Sphere()]),
        Hull([Cube(), Sphere()]),
        Minkowski([Cube(), Sphere()]),
        Translate((1, 2, 3), [Cube()]),
        Rotate((1, 2, 3), [Cube()]),
        Scale((1, 2, 3), [Cube()]),
        Mirror((1, 0, 0), [Cube()]),
        Color((1, 0, 0, 1), [Cube()]),
        Group([Cube()], name="base"),
    ]
    for node in nodes:
        source = emit(node)
        assert source.startswith("// generated by phimech 0.1.0")
        assert source.endswith("\n")


def test_emit_text_group() -> None:
    spec = {
        "text": 'A "quoted" label',
        "size": 6,
        "depth": 0.6,
        "font": "Liberation Sans",
        "halign": "center",
        "valign": "center",
    }
    node = Group(name="text:" + json.dumps(spec))
    assert emit(node) == (
        "// generated by phimech 0.1.0 — do not edit\n"
        'linear_extrude(height=0.6) text("A \\"quoted\\" label", size=6, '
        'font="Liberation Sans", halign="center", valign="center");\n'
    )


def test_step_import_is_rejected() -> None:
    try:
        emit(Import("vendor.step"))
    except BackendError as exc:
        assert str(exc) == "STEP import requires the freecad backend"
    else:
        raise AssertionError("STEP imports must not be sent to OpenSCAD")


def test_render_rejects_zero_area_polygon_before_binary_lookup() -> None:
    node = LinearExtrude(1, [Polygon(((0, 0), (1, 0), (2, 0)))])
    backend = OpenSCADBackend()
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / "invalid.stl"
        with patch(
            "phimech.backends.openscad._candidate_binary",
            side_effect=AssertionError("binary lookup must not run"),
        ):
            try:
                backend.render(node, output, "stl")
            except BackendError as exc:
                assert str(exc) == (
                    "invalid CSG AST: "
                    "root.children[0] polygon outline encloses zero area"
                )
            else:
                raise AssertionError("expected fail-fast polygon validation")


def test_render_cube_and_measure() -> None:
    backend = _require_openscad()
    with tempfile.TemporaryDirectory(prefix="phimech-test-openscad-") as directory:
        result = backend.render(Cube((10, 20, 30)), Path(directory) / "cube.stl", "stl")
        measurement = measure_stl(result.path)
    if pytest:
        assert measurement.volume == pytest.approx(6000.0, abs=0.5)
    else:
        assert abs(measurement.volume - 6000.0) <= 0.5
    assert measurement.bbox.min == (0.0, 0.0, 0.0)
    assert measurement.bbox.max == (10.0, 20.0, 30.0)


def test_render_difference_has_less_volume() -> None:
    backend = _require_openscad()
    node = Cube((10, 20, 30)) - Cylinder(h=40, r=2, center=True).translate((5, 10, 15))
    # No temp dir needed: measure() renders into its own scratch space.
    measurement = backend.measure(node)
    assert measurement.volume < 6000.0


