def test_measure_ascii_tetrahedron() -> None:
    ascii_stl = """solid tetra
  facet normal 0 0 -1
    outer loop
      vertex 0 0 0
      vertex 0 1 0
      vertex 1 0 0
    endloop
  endfacet
  facet normal 0 -1 0
    outer loop
      vertex 0 0 0
      vertex 1 0 0
      vertex 0 0 1
    endloop
  endfacet
  facet normal -1 0 0
    outer loop
      vertex 0 0 0
      vertex 0 0 1
      vertex 0 1 0
    endloop
  endfacet
  facet normal 1 1 1
    outer loop
      vertex 1 0 0
      vertex 0 1 0
      vertex 0 0 1
    endloop
  endfacet
endsolid tetra
"""
    with tempfile.TemporaryDirectory(prefix="phimech-test-stl-") as directory:
        path = Path(directory) / "tetra.stl"
        path.write_text(ascii_stl, encoding="ascii")
        measurement = measure_stl(path)
    assert abs(measurement.volume - (1.0 / 6.0)) < 1e-12
    assert measurement.bbox.min == (0.0, 0.0, 0.0)
    assert measurement.bbox.max == (1.0, 1.0, 1.0)


def test_emit_rotate_is_positional_not_named_v() -> None:
    """`rotate` must be positional: `rotate(v=...)` is the AXIS form and rotates nothing.

    Regression for the bug that collapsed every rounded enclosure into a wedge. Kept as a
    string assertion so it fails without needing the openscad binary.
    """
    text = emit(Rotate((0, 90, 0), [Cylinder(h=20, r=2)]))
    assert "rotate([0, 90, 0])" in text
    assert "rotate(v=" not in text


def test_rotate_actually_rotates_geometry() -> None:
    """The same claim, proven through the real kernel: a Z cylinder becomes an X cylinder."""
    backend = _require_openscad()
    node = Rotate((0, 90, 0), [Cylinder(h=20, r=2)])
    with tempfile.TemporaryDirectory(prefix="phimech-test-rot-") as directory:
        result = backend.render(node, Path(directory) / "rot.stl")
        measurement = measure_stl(result.path)
    size = measurement.bbox.size
    assert abs(size[0] - 20.0) < 0.1, "expected 20 mm along X after rotate, got {}".format(size)
    assert size[2] < 5.0, "expected the 20 mm extent to leave Z, got {}".format(size)


def _open_shell_stl(path: Path) -> None:
    """Write a single triangle: a deliberately non-manifold surface, like a vendor web mesh."""
    text = "\n".join(
        [
            "solid open",
            "  facet normal 0 0 1",
            "    outer loop",
            "      vertex 0 0 0",
            "      vertex 20 0 0",
            "      vertex 0 20 0",
            "    endloop",
            "  endfacet",
            "endsolid open",
            "",
        ]
    )
    path.write_text(text, encoding="utf-8")


def test_preview_png_keeps_an_imported_open_shell_visible() -> None:
    """`preview=True` must not evaluate to a manifold, or open reference meshes disappear.

    Regression for the full-assembly scene rendering with the aircraft body missing: PNG export
    forced `--render true`, OpenSCAD failed the manifold conversion of the imported vendor mesh,
    and the resulting image showed only the payload. The preview path must still draw it, while
    the default path stays on full evaluation.
    """
    backend = _require_openscad()
    with tempfile.TemporaryDirectory(prefix="phimech-test-preview-") as directory:
        root = Path(directory)
        shell = root / "open.stl"
        _open_shell_stl(shell)
        node = Group([Import(path=str(shell)), Cube(size=(4, 4, 4))])

        preview_png = root / "preview.png"
        backend.render(node, preview_png, "png", preview=True)
        solid_png = root / "solid.png"
        backend.render(node, solid_png, "png")

        preview_bytes = preview_png.read_bytes()
        solid_bytes = solid_png.read_bytes()

    assert preview_bytes, "preview render produced no PNG"
    assert solid_bytes, "default render produced no PNG"
    # The open triangle is 20 mm across against a 4 mm cube, so including it changes the framed
    # image substantially. Identical bytes would mean preview silently dropped it too.
    assert preview_bytes != solid_bytes, (
        "preview and manifold renders are byte-identical; preview is still evaluating to a "
        "manifold and dropping the imported open shell"
    )


def _run_direct() -> int:
    tests = [value for name, value in globals().items() if name.startswith("test_")]
    failures = 0
    for test in tests:
        try:
            test()
        except _Skipped as exc:
            print("SKIP {}: {}".format(test.__name__, exc))
        except Exception as exc:  # pragma: no cover - only used by direct invocation
            failures += 1
            print("FAIL {}: {}".format(test.__name__, exc))
        else:
            print("PASS {}".format(test.__name__))
    return failures


if __name__ == "__main__":
    raise SystemExit(_run_direct())
