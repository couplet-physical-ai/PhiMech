def test_vendored_copy_is_complete_and_pinned() -> None:
    assert bosl2.BOSL2_DIR.is_dir(), bosl2.BOSL2_DIR
    files = bosl2.include_files()
    for required in ("BOSL2/std.scad", "BOSL2/screws.scad", "BOSL2/threading.scad",
                     "BOSL2/rounding.scad", "BOSL2/skin.scad", "BOSL2/shapes3d.scad"):
        assert required in files, "{} is not vendored".format(required)
    assert (bosl2.BOSL2_DIR / "LICENSE").is_file(), "BSD-2 LICENSE must travel with the copy"
    licence = (bosl2.BOSL2_DIR / "LICENSE").read_text(encoding="utf-8")
    assert "BSD 2-Clause License" in licence and "Revar Desmera" in licence

    # Only library files: tests/, examples/, images/ from upstream would be a 15 MB mistake.
    stray = sorted(
        p.name for p in bosl2.BOSL2_DIR.iterdir()
        if not (p.suffix == ".scad" and p.is_file()) and p.name not in ("LICENSE", "VENDORED.md")
    )
    assert not stray, "unexpected files in the vendored copy: {}".format(stray)
    size = bosl2.vendored_size_bytes()
    assert 0 < size < VENDOR_SIZE_LIMIT, "vendored copy is {} bytes".format(size)

    pin = bosl2.pinned()
    assert pin["commit"] and re.fullmatch(r"[0-9a-f]{40}", pin["commit"]), pin
    assert pin["commit_date"] and pin["commit_date"].startswith("20"), pin
    assert pin["version"] and pin["version"].startswith("[2,"), pin
    # The pin must match the copy: version.scad is upstream's own statement of its version.
    version_scad = (bosl2.BOSL2_DIR / "version.scad").read_text(encoding="utf-8")
    assert "BOSL_VERSION = {};".format(pin["version"]) in version_scad, (
        "VENDORED.md pins {} but version.scad disagrees".format(pin["version"]))

    notices = (REPO / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
    assert "BOSL2" in notices and "BSD 2-Clause" in notices and "Revar Desmera" in notices
    assert "phimech/vendor/BOSL2/" in notices


def test_curated_modules_exist_in_vendored_source() -> None:
    """The MCP table is hand-written; a refresh that renames a module must fail here, not in use."""
    assert len(bosl2.CURATED_MODULES) >= 14, len(bosl2.CURATED_MODULES)
    names = [entry["module"] for entry in bosl2.CURATED_MODULES]
    assert len(set(names)) == len(names), "duplicate curated module"
    for required in ("threaded_rod", "screw", "screw_hole", "nut", "path_sweep", "offset_sweep",
                     "cuboid", "cyl", "tube", "prismoid", "linear_sweep", "skin"):
        assert required in names, "{} missing from the curated table".format(required)
    for entry in bosl2.CURATED_MODULES:
        defined_in = bosl2.defines_module(entry["module"])
        assert defined_in, "{} is not defined in any vendored file".format(entry["module"])
        bosl2.resolve_include(entry["include"])  # raises if the include is not vendored
        assert entry["summary"].strip() and entry["args"], entry["module"]


