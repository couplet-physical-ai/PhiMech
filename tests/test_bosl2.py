"""BOSL2 lane gate: the vendored copy, the `scad_module` node, both backends, and the examples.

Runs both ways, like the rest of the suite::

    /usr/bin/python3 tests/test_bosl2.py     # direct, prints the measured numbers, exit = failures
    pytest tests/test_bosl2.py

The numeric gate (BOSL2 rendering regression): the M3 rod example built
through BOSL2 must measure within **±0.1 mm of Ø3.0 and 12.0 long**, and the swept example must be
watertight with volume > 0. Tests that need the OpenSCAD binary skip cleanly without it; everything
else - validation, emission, the FreeCAD refusal, the licence paperwork - runs on a bare machine.
"""

