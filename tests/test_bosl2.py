class _Skipped(Exception):
    pass


def _skip(message: str) -> None:
    # pytest.skip() derives from BaseException and would crash the direct runner; PYTEST_CURRENT_TEST
    # tells "pytest is driving" from "pytest is merely installed" (see test_backend_openscad.py).
    if pytest is not None and _os.environ.get("PYTEST_CURRENT_TEST"):
        pytest.skip(message)
    raise _Skipped(message)


def _require_openscad() -> OpenSCADBackend:
    backend = OpenSCADBackend()
    if not backend.available():
        _skip("openscad is not installed")
    return backend


def _load(path: Path) -> ast.Node:
    return from_dict(json.loads(path.read_text(encoding="utf-8")))


def _render_and_inspect(backend: OpenSCADBackend, node: ast.Node) -> Tuple[object, bool, int, int]:
    """Render to STL once and return (measurement, watertight, open_edges, shells)."""
    with tempfile.TemporaryDirectory(prefix="phimech-bosl2-") as tmp:
        stl = Path(tmp) / "part.stl"
        backend.render(node, stl, "stl")
        from phimech.backends.openscad import measure_stl

        measurement = measure_stl(stl)
        tris = mesh.read_stl(str(stl))
        watertight, open_edges = mesh.is_watertight(tris)
        shells = mesh.count_shells(tris)
    return measurement, watertight, open_edges, shells


