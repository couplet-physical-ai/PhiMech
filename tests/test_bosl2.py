def _mcp_tools() -> List[Tuple[str, List[str], str]]:
    tree = pyast.parse(TOOLS_MODULE.read_text(encoding="utf-8"))
    found: List[Tuple[str, List[str], str]] = []
    for node in pyast.walk(tree):
        if not isinstance(node, (pyast.FunctionDef, pyast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            target = decorator.func if isinstance(decorator, pyast.Call) else decorator
            if isinstance(target, pyast.Attribute) and target.attr == "tool":
                args = [a.arg for a in node.args.args if a.arg not in ("self", "cls")]
                found.append((node.name, args, pyast.get_docstring(node) or ""))
                break
    return found


def test_mcp_module_exposes_register_and_documented_tools() -> None:
    assert TOOLS_MODULE.is_file()
    tree = pyast.parse(TOOLS_MODULE.read_text(encoding="utf-8"))
    functions = {n.name for n in pyast.walk(tree) if isinstance(n, pyast.FunctionDef)}
    assert "register" in functions, "phimech/mcp/tools_bosl2.py must expose register(mcp)"
    tools = _mcp_tools()
    names = [name for name, _, _ in tools]
    assert "bosl2_modules" in names, names
    limit_markers = ("limits:", "cannot", "does not", "never", "refuses", "only")
    for name, args, doc in tools:
        low = doc.lower()
        assert len(doc.split()) >= 25, "{}: description too thin".format(name)
        assert " mm" in low or "millimetre" in low, "{}: names no unit".format(name)
        assert any(marker in low for marker in limit_markers), "{}: states no limit".format(name)
        assert "openscad" in low and "step" in low, "{}: must say OpenSCAD-only, no STEP".format(name)
        path_args = [a for a in args if a.endswith(("_path", "_dir")) or a == "path"]
        if path_args:
            assert "absolute" in low, "{}: path args must be documented as absolute".format(name)


