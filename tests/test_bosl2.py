def test_openscadpath_reaches_the_subprocess_with_ours_first() -> None:
    with patch.dict(_os.environ, {"OPENSCADPATH": "/somewhere/else"}):
        value = openscad_env()["OPENSCADPATH"]
    entries = value.split(_os.pathsep)
    assert entries[0] == str(VENDOR_DIR), value
    assert "/somewhere/else" in entries, value
    with patch.dict(_os.environ, {}, clear=False):
        _os.environ.pop("OPENSCADPATH", None)
        assert openscad_env()["OPENSCADPATH"] == str(VENDOR_DIR)
    assert (VENDOR_DIR / "BOSL2" / "std.scad").is_file()


def test_freecad_refuses_scad_module_before_any_subprocess() -> None:
    backend = FreeCADBackend()
    assert "scad_module" in backend.UNSUPPORTED
    assert "scad_module" in backend.doctor()["unsupported"]
    rod = _load(ROD_EXAMPLE)
    reason = backend.can_render(Union([Cube(), Translate((5, 0, 0), [rod])]))
    assert reason, "can_render accepted a scad_module tree"
    assert "scad_module" in reason and "threaded_rod" in reason and "BOSL2/threading.scad" in reason
    assert "openscad" in reason.lower() and "step" in reason.lower()

    def never(*args, **kwargs):  # pragma: no cover - only runs if the refusal regressed
        raise AssertionError("freecadcmd was launched for a scad_module tree")

    # Binary hidden on purpose: the refusal must come before "freecadcmd not found".
    with patch("phimech.backends.freecad.subprocess.run", never), \
            patch.object(FreeCADBackend, "binary", property(lambda self: None)):
        with tempfile.TemporaryDirectory() as tmp:
            for call in (
                lambda: backend.render(rod, Path(tmp) / "rod.step"),
                lambda: backend.measure(rod),
                lambda: backend.render_many(rod, {"stl": Path(tmp) / "rod.stl"}),
            ):
                try:
                    call()
                except BackendError as exc:
                    text = str(exc)
                    assert "scad_module" in text and "openscad backend" in text, text
                    assert "not found" not in text, text
                else:
                    raise AssertionError("FreeCAD accepted a scad_module tree")


