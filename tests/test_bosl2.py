def test_scad_module_round_trips_through_json() -> None:
    node = ScadModule(
        "threaded_rod", {"d": 3, "l": 12, "pitch": 0.5, "$fn": 48, "bevel": None},
        include="BOSL2/threading.scad", children=[Cube((1, 1, 1))],
    )
    assert node.kind == "scad_module"
    assert isinstance(node.children, tuple) and isinstance(node.args, dict)
    again = from_dict(json.loads(node.to_json()))
    assert again == node
    assert "scad_module" in ast.NODE_TYPES and "scad_module" in ast.LIBRARY
    assert ast.is_2d(node) is False
    assert [n.kind for n in ast.walk(Union([node, Cube()]))] == ["union", "scad_module", "cube", "cube"]


def test_validation_rejects_path_escaping_include() -> None:
    escapes = (
        "../../phimech/cli.py", "../vendor/BOSL2/std.scad", "BOSL2/../../csg/ast.scad",
        "/etc/passwd.scad", "BOSL2/./std.scad", "BOSL2//std.scad", "BOSL2\\std.scad",
        "BOSL2/std.scad>; cube(9);", "", "BOSL2/does-not-exist.scad",
    )
    for include in escapes:
        errors = [e for e in validate(ScadModule("cuboid", {"size": 1}, include=include))
                  if not e.startswith("warn:")]
        assert errors, "include {!r} was accepted".format(include)
        assert "include" in errors[0], errors
    # and the resolver itself never returns a path outside phimech/vendor
    for include in bosl2.include_files():
        resolved = bosl2.resolve_include(include)
        resolved.relative_to(VENDOR_DIR.resolve())


def test_validation_rejects_source_smuggling_and_non_literals() -> None:
    bad = {
        "module is a call": ScadModule("cube(); echo", {}),
        "module starts with digit": ScadModule("3d", {}),
        "argument name is a call": ScadModule("cuboid", {"size=1); cube(": 1}),
        "argument is an object": ScadModule("cuboid", {"size": {"x": 1}}),
        "argument is NaN": ScadModule("cuboid", {"size": float("nan")}),
        "argument nests absurdly": ScadModule("skin", {"profiles": [[[[[1]]]]]}),
    }
    for label, node in bad.items():
        errors = [e for e in validate(node) if not e.startswith("warn:")]
        assert errors, "{}: accepted".format(label)
    # while the legitimate shapes pass
    assert_valid(ScadModule("path_sweep", {"shape": [[0, 0], [1, 0], [0, 1]], "path": [[0, 0], [5, 0]],
                                           "caps": True, "method": "incremental", "twist": None}))
    assert_valid(ScadModule("skin", {"profiles": [[[0, 0, 0], [1, 0, 0], [0, 1, 0]],
                                                  [[0, 0, 5], [1, 0, 5], [0, 1, 5]]]}))
    assert_valid(_load(ROD_EXAMPLE))
    assert_valid(_load(HANDLE_EXAMPLE))


def test_emit_matches_golden_text() -> None:
    """Includes deduplicated with std.scad first; every literal kind formatted; children blocked."""
    tree = Difference([
        ScadModule("cuboid", {"size": [20, 12, 6], "rounding": 1.5, "edges": "Z"}),
        Translate((0, 0, -4), [
            ScadModule("screw_hole", {"spec": "M3", "length": 20, "thread": False, "head": "socket"},
                       include="BOSL2/screws.scad"),
        ]),
        ScadModule("threaded_rod", {"d": 3, "l": 12, "pitch": 0.5, "internal": True, "bevel": None,
                                    "$fn": 48}, include="BOSL2/threading.scad"),
        ScadModule("cuboid", {"size": [8, 2, 8]}, include="BOSL2/screws.scad",
                   children=[Cube((1, 1, 1))]),
    ])
    assert includes_for(tree) == ["BOSL2/std.scad", "BOSL2/screws.scad", "BOSL2/threading.scad"]
    assert emit(tree) == (
        _HEADER
        + "include <BOSL2/std.scad>\n"
        + "include <BOSL2/screws.scad>\n"
        + "include <BOSL2/threading.scad>\n"
        + "difference() {\n"
        + '  cuboid(size=[20, 12, 6], rounding=1.5, edges="Z");\n'
        + "  translate([0, 0, -4]) {\n"
        + '    screw_hole(spec="M3", length=20, thread=false, head="socket");\n'
        + "  }\n"
        + "  threaded_rod(d=3, l=12, pitch=0.5, internal=true, bevel=undef, $fn=48);\n"
        + "  cuboid(size=[8, 2, 8]) {\n"
        + "    cube(size=[1, 1, 1], center=false);\n"
        + "  }\n"
        + "}\n"
    )
    # the rod example, exactly
    assert emit(_load(ROD_EXAMPLE)) == (
        _HEADER
        + "include <BOSL2/std.scad>\n"
        + "include <BOSL2/threading.scad>\n"
        + "threaded_rod(d=3, l=12, pitch=0.5, $fn=48);\n"
    )


def test_emit_of_plain_trees_is_unchanged() -> None:
    """The golden renders depend on library-free trees emitting exactly what they always did."""
    assert emit(Cube((10, 20, 30))) == _HEADER + "cube(size=[10, 20, 30], center=false);\n"
    assert includes_for(Union([Cube(), Cube()])) == []


def test_emitter_refuses_non_identifiers_independently_of_validation() -> None:
    for node in (ScadModule("cube(); echo", {}), ScadModule("cuboid", {"a;b": 1})):
        try:
            emit(node)
        except BackendError as exc:
            assert "identifier" in str(exc)
        else:
            raise AssertionError("emitter accepted a non-identifier")
    try:
        emit(ScadModule("cuboid", {}, include="../../x.scad"))
    except BackendError as exc:
        assert "include" in str(exc)
    else:
        raise AssertionError("emitter accepted a path-escaping include")


