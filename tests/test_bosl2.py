def test_m3_rod_measures_to_spec() -> None:
    """THE GATE: major diameter within ±0.1 mm of 3.0, length within ±0.1 mm of 12.0, watertight."""
    backend = _require_openscad()
    rod = _load(ROD_EXAMPLE)
    measurement, watertight, open_edges, shells = _render_and_inspect(backend, rod)
    sx, sy, sz = measurement.bbox.size  # type: ignore[attr-defined]
    print("    M3 rod: bbox size x={:.4f} y={:.4f} z={:.4f} mm, volume {:.3f} mm3, "
          "watertight={} open_edges={} shells={}".format(
              sx, sy, sz, measurement.volume, watertight, open_edges, shells))  # type: ignore[attr-defined]
    assert abs(sx - M3_MAJOR_DIAMETER) <= TOLERANCE, "major diameter (x) {:.4f} mm".format(sx)
    assert abs(sy - M3_MAJOR_DIAMETER) <= TOLERANCE, "major diameter (y) {:.4f} mm".format(sy)
    assert abs(sz - ROD_LENGTH) <= TOLERANCE, "length (z) {:.4f} mm".format(sz)
    assert watertight and open_edges == 0, "rod STL has {} open edges".format(open_edges)
    assert shells == 1, "rod STL has {} shells".format(shells)
    # A threaded rod is less than its enveloping cylinder (pi * 1.5^2 * 12 = 84.8 mm3) and far
    # more than the minor-diameter core (pi * 1.19^2 * 12 = 53.4 mm3 for M3): sanity on the profile.
    assert 53.0 < measurement.volume < 85.0, measurement.volume  # type: ignore[attr-defined]


def test_swept_handle_is_manifold_with_volume() -> None:
    backend = _require_openscad()
    handle = _load(HANDLE_EXAMPLE)
    measurement, watertight, open_edges, shells = _render_and_inspect(backend, handle)
    sx, sy, sz = measurement.bbox.size  # type: ignore[attr-defined]
    print("    swept handle: bbox size x={:.3f} y={:.3f} z={:.3f} mm, volume {:.3f} mm3, "
          "watertight={} open_edges={} shells={}".format(
              sx, sy, sz, measurement.volume, watertight, open_edges, shells))  # type: ignore[attr-defined]
    assert measurement.volume > 0.0  # type: ignore[attr-defined]
    assert watertight and open_edges == 0, "handle STL has {} open edges".format(open_edges)
    assert shells == 1, "handle STL has {} shells (grip and feet must fuse)".format(shells)
    # The grip is a Ø5 tube: the part must be exactly 5 mm tall plus nothing, until the 8 mm feet.
    assert abs(sz - 8.0) < 0.05 and abs(sx - 38.0) < 0.05, (sx, sy, sz)


