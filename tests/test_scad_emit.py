"""Focused, dependency-free tests for deterministic OpenSCAD source emission.

These tests exercise only the pure-Python emitter.  They never discover or launch an
OpenSCAD executable, so source-generation regressions stay testable on a bare machine.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from phimech.backends.scad_emit import emit
from phimech.csg.ast import Cube, Group


_HEADER = "// generated by phimech 0.1.0 — do not edit\n"


def test_group_label_cannot_inject_open_scad_source() -> None:
    """A line break in metadata must not turn the rest of the label into source."""
    node = Group([Cube()], name="base\ncube(size=[999,999,999]);")

    assert emit(node) == (
        _HEADER
        + '// "base\\ncube(size=[999,999,999]);"\n'
        + "union() {\n"
        + "  cube(size=[1, 1, 1], center=false);\n"
        + "}\n"
    )


def test_group_label_controls_stay_on_one_printable_comment_line() -> None:
    """Every C0/C1 control and Unicode line separator is escaped deterministically."""
    controls = list(range(0x20)) + list(range(0x7F, 0xA0)) + [0x2028, 0x2029]

    for codepoint in controls:
        source = emit(Group([Cube()], name="left{}right".format(chr(codepoint))))
        lines = source.splitlines()

        assert len(lines) == 5, "U+{:04X} created an extra source line".format(codepoint)
        assert lines[1].startswith('// "left')
        assert lines[1].endswith('right"')
        assert all(0x20 <= ord(character) <= 0x7E for character in lines[1])
        assert lines[2:] == [
            "union() {",
            "  cube(size=[1, 1, 1], center=false);",
            "}",
        ]


def _run_direct() -> int:
    failures = 0
    for name, test in sorted(globals().items()):
        if not name.startswith("test_") or not callable(test):
            continue
        try:
            test()
        except Exception as exc:  # pragma: no cover - direct-run reporting only
            failures += 1
            print("FAIL {}: {}".format(name, exc))
        else:
            print("PASS {}".format(name))
    return failures


if __name__ == "__main__":
    raise SystemExit(_run_direct())
