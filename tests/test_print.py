# Endpoint paths, G-code commands, and Klipper macro names that would move plastic or heat.
# Bare English words ("cancel", "temperature") are deliberately NOT in this list: the module
# docstring has to be able to say what it refuses to do.
_FORBIDDEN_TOKENS = (
    "/printer/print/start",
    "/printer/print/pause",
    "/printer/print/resume",
    "/printer/print/cancel",
    "/printer/emergency_stop",
    "/printer/gcode/script",
    "/printer/firmware_restart",
    "/api/printer/command",
    "/machine/shutdown",
    "/machine/reboot",
    "print/start",
    "emergency_stop",
    "gcode/script",
    "SET_HEATER_TEMPERATURE",
    "TEMPERATURE_WAIT",
    "START_PRINT",
    "CANCEL_PRINT",
    "PAUSE",
    "RESUME",
    "M104",
    "M109",
    "M140",
    "M190",
    "M112",
    "G28",
    "G0 ",
    "G1 ",
    "M84",
)

_FORBIDDEN_NAMES = (
    "start_print",
    "cancel_print",
    "pause_print",
    "resume_print",
    "abort",
    "emergency_stop",
    "set_temperature",
    "set_temp",
    "home",
    "home_axes",
    "move",
    "move_axis",
    "run_gcode",
    "send_gcode",
    "gcode_script",
    "extrude",
)


def _code_strings(source: str):
    """Every string literal in the module EXCEPT docstrings, plus attribute/name identifiers.

    Docstrings are excluded on purpose: the safety contract is written in prose there, and a
    naive grep for the word "cancel" would flag the very sentence promising not to cancel.
    """
    tree = ast.parse(source)
    docstrings = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = getattr(node, "body", [])
            if body and isinstance(body[0], ast.Expr):
                value = body[0].value
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    docstrings.add(id(value))
    strings = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            if id(node) not in docstrings:
                strings.append(node.value)
        elif isinstance(node, ast.Attribute):
            strings.append(node.attr)
        elif isinstance(node, ast.Name):
            strings.append(node.id)
    return strings


def test_printer_module_has_no_print_control() -> None:
    """The safety contract, machine-checked against this module's own source."""
    source = Path(printer.__file__).read_text(encoding="utf-8")
    strings = _code_strings(source)
    for token in _FORBIDDEN_TOKENS:
        for value in strings:
            assert token not in value, "print-control token {!r} found in code string {!r}".format(
                token, value
            )
    exported = [name for name in dir(printer) if not name.startswith("_")]
    for name in exported:
        assert name.lower() not in _FORBIDDEN_NAMES, "{} must not exist in printer.py".format(name)
    # No HTTP verb other than GET and the single POST used by the upload.
    assert source.count('method="POST"') == 1, "exactly one POST (the upload) is allowed"
    for verb in ('method="DELETE"', 'method="PUT"', 'method="PATCH"'):
        assert verb not in source, "{} must not be used".format(verb)


def test_the_no_print_control_check_can_actually_fail() -> None:
    """Mutation check: prove the scanner catches a violation instead of always passing."""
    violation = (
        '"""Docstring mentioning start_print and M104 must stay invisible."""\n'
        "def go():\n"
        '    return _request("/printer/print/start")\n'
    )
