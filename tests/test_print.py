def test_parse_duration_all_observed_formats() -> None:
    cases = {
        "18m 18s": 18 * 60 + 18,       # the format in the verified hand-run
        "28m 8s": 28 * 60 + 8,          # the format this module's own slice produced
        "1h 2m 3s": 3723,
        "2d 1h": 2 * 86400 + 3600,
        "45s": 45,
        "28m8s": 28 * 60 + 8,           # no space
        "1688": 1688,                   # bare seconds (the 3MF `prediction` value)
        "3h": 10800,
        "  7m 30s  ": 450,
    }
    for text, expected in cases.items():
        actual = slicer.parse_duration(text)
        assert actual == expected, "{!r} -> {} (want {})".format(text, actual, expected)
    for empty in ("", "   ", "unknown", None):
        assert slicer.parse_duration(empty) is None, "{!r} should not parse".format(empty)


def test_format_duration_round_trips() -> None:
    for seconds in (0, 45, 1688, 3723, 176400):
        text = slicer.format_duration(seconds)
        assert slicer.parse_duration(text) == seconds, "{} -> {!r}".format(seconds, text)
    assert slicer.format_duration(1688) == "28m 8s"


