def _synthetic_pack(root: Path) -> None:
    """A miniature vendor pack: same shape as Qidi's, including the filament/X4 trap."""
    (root / "machine").mkdir(parents=True)
    (root / "process").mkdir(parents=True)
    (root / "filament" / "X4").mkdir(parents=True)

    def dump(path: Path, data: dict) -> None:
        path.write_text(json.dumps(data), encoding="utf-8")

    dump(
        root / "machine" / "Test Max 4 0.4 nozzle.json",
        {
            "type": "machine",
            "name": "Test Max 4 0.4 nozzle",
            "from": "system",
            "instantiation": "true",
            "printer_model": "Test Max 4",
            "nozzle_diameter": ["0.4"],
            "printable_height": 340,
        },
    )
    dump(
        root / "process" / "process_common.json",
        {
            "type": "process",
            "name": "process_common",
            "instantiation": "false",
            "layer_height": "0.2",
            "sparse_infill_density": "15%",
        },
    )
    for height, style in (("0.20", "Standard"), ("0.08", "Extra Fine")):
        data = {
            "type": "process",
            "name": "{}mm {} @Test Max 4".format(height, style),
            "from": "system",
            "instantiation": "true",
            "inherits": "process_common",
            "compatible_printers": ["Test Max 4 0.4 nozzle"],
        }
        if style != "Standard":  # mirrors the vendor pack: Standard inherits its height
            data["layer_height"] = height
        dump(root / "process" / "{}mm {} @Test Max 4.json".format(height, style), data)

    # The chain that the CLI refuses to walk: density and temperatures live two levels up.
    dump(
        root / "filament" / "X4" / "filament_x4_common.json",
        {
            "type": "filament",
            "name": "filament_x4_common",
            "instantiation": "false",
            "filament_type": ["PLA"],
            "filament_density": ["1.24"],
            "filament_diameter": ["1.75"],
            "nozzle_temperature": ["210"],
            "hot_plate_temp": ["60"],
        },
    )
    dump(
        root / "filament" / "X4" / "TEST PETG Basic @Max 4.json",
        {
            "type": "filament",
            "name": "TEST PETG Basic@Max 4-Series",
            "instantiation": "false",
            "inherits": "filament_x4_common",
            "filament_type": ["PETG"],
            "nozzle_temperature": ["240"],
            "hot_plate_temp": ["70"],
        },
    )
    dump(
        root / "filament" / "X4" / "TEST PETG Basic @Test Max 4 0.4 nozzle.json",
        {
            "type": "filament",
            "name": "TEST PETG Basic @Test Max 4 0.4 nozzle",
            "from": "system",
            "instantiation": "true",
            "inherits": "TEST PETG Basic@Max 4-Series",
            "compatible_printers": ["Test Max 4 0.4 nozzle"],
        },
    )
    # A same-named decoy in filament/ root, targeting a DIFFERENT printer. A naive
    # `filament/*.json` glob picks this one and slices with the wrong preset.
    dump(
        root / "filament" / "TEST PETG Basic @Other 0.4 nozzle.json",
        {
            "type": "filament",
            "name": "TEST PETG Basic @Other 0.4 nozzle",
            "from": "system",
            "instantiation": "true",
            "inherits": "filament_x4_common",
            "compatible_printers": ["Other Printer 0.4 nozzle"],
        },
    )


def test_flatten_resolves_the_inherits_chain() -> None:
    """The whole reason grams were 0.00: the leaf carries none of the numbers."""
    with tempfile.TemporaryDirectory(prefix="phimech-test-profiles-") as directory:
        root = Path(directory) / "pack"
        _synthetic_pack(root)
        profiles.clear_cache()
        leaf = json.loads(
            (
                root / "filament" / "X4" / "TEST PETG Basic @Test Max 4 0.4 nozzle.json"
            ).read_text(encoding="utf-8")
        )
        assert "filament_density" not in leaf, "fixture must reproduce the bare-leaf shape"
        merged = profiles.flatten("TEST PETG Basic @Test Max 4 0.4 nozzle", root)
        profiles.clear_cache()
    assert merged["filament_density"] == ["1.24"], "density must come from the grandparent"
    assert merged["filament_type"] == ["PETG"], "the child must override the parent's PLA"
    assert merged["nozzle_temperature"] == ["240"]
    assert merged["hot_plate_temp"] == ["70"]
    assert "inherits" not in merged, "the CLI treats the file as a complete preset"
    assert merged["from"] == "system", "the CLI rejects a preset with no `from`"
    assert merged["instantiation"] == "true"


