        assert not (Path(directory) / "out" / "plate_1.gcode").exists()
        assert not (Path(directory) / "out" / "00000.log").exists()
        log = (Path(directory) / "out" / "cube.slicer.log").read_text()
        assert log.strip(), "slicer.log must capture the slicer messages"

