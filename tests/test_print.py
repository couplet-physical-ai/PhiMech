def test_parse_gcode_metadata_reads_both_ends_of_a_large_file() -> None:
    """The parser reads only the head and tail; a big body must not hide the summary."""
    filler = "G1 X{} Y{} E0.1\n".format(1, 1) * 120000
    text = _GOOD_HEADER.replace("G1 X1 Y1\n", filler)
    with tempfile.TemporaryDirectory(prefix="phimech-test-print-") as directory:
        path = _write(text, directory)
        assert path.stat().st_size > 1024 * 1024, "fixture must exceed the head window"
        meta = slicer.parse_gcode_metadata(path)
    assert meta["layer_count"] == 100, "header block (file head) was missed"
    assert meta["print_time_s"] == 1688, "summary (file tail) was missed"
    assert meta["filament_type"] == "PETG", "CONFIG_BLOCK (file tail) was missed"


def test_zero_gram_header_is_detected_not_reported() -> None:
    """`0.00 g` must never survive as a mass: it parses to 0.0, which is falsy on purpose."""
    with tempfile.TemporaryDirectory(prefix="phimech-test-print-") as directory:
        meta = slicer.parse_gcode_metadata(_write(_ZERO_GRAM_HEADER, directory))
    assert meta["filament_g"] == 0.0
    assert not meta["filament_g"], "a zero mass must be falsy so the fallback chain triggers"
    assert meta["filament_mm"] == 1138.80, "length is still trustworthy and drives the estimate"


def test_estimate_grams_matches_the_measured_slice() -> None:
    """1138.8 mm of 1.75 mm PETG at 1.24 g/cm3 -> the 3.40 g OrcaSlicer reported."""
    grams = slicer.estimate_grams(1138.80, 1.75, 1.24)
    assert abs(grams - 3.40) < 0.02, "estimate {} g should land on the measured 3.40 g".format(
        grams
    )
    assert slicer.estimate_grams(0.0, 1.75, 1.24) == 0.0


