def test_slice_stl_isolates_per_part_outputs_and_keeps_the_root_clean() -> None:
    """Regression: every slice wrote the same ``plate_1.gcode`` + ``00000.log`` into the build root.

    OrcaSlicer's subprocess is faked; it behaves like the real CLI (``plate_1.gcode`` in
    ``--outputdir``, ``00000.log`` in the CWD, nothing on stdout).
    """
    import subprocess
    import types

    def fake_run(command, **kwargs):
        outdir = Path(command[command.index("--outputdir") + 1])
        model = Path(command[-1])
        assert Path(kwargs["cwd"]) == outdir, "the CLI must run in its scratch outputdir"
        assert outdir.name != "build", "must not slice directly in the shared build root"
        (outdir / command[command.index("--export-3mf") + 1]).write_bytes(b"3mf-" + model.read_bytes())
        (outdir / "plate_1.gcode").write_text(_GOOD_HEADER + "; part " + model.stem + "\n")
        (outdir / "00000.log").write_text("slicer message for " + model.stem + "\n")
        return types.SimpleNamespace(returncode=0, stdout=b"")

    resolved = types.SimpleNamespace(
        filament_density=1.24, filament_diameter_mm=1.75, layer_height_mm=0.2,
        nozzle_temp_c=240, bed_temp_c=70, filament_type="PETG",
        machine="m", process="p", filament="f",
    )

    def fake_flatten(_resolved, directory, extra_settings=None):
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        return {k: directory / (k + ".json") for k in ("machine", "process", "filament")}

    saved = (slicer.find_orcaslicer, slicer._profiles.resolve,
             slicer._profiles.write_flattened, subprocess.run)
    slicer.find_orcaslicer = lambda: Path("/fake/orca")
    slicer._profiles.resolve = lambda **_kw: resolved
    slicer._profiles.write_flattened = fake_flatten
    subprocess.run = fake_run
    try:
        with tempfile.TemporaryDirectory(prefix="phimech-test-slice-") as directory:
            root = Path(directory)
            build = root / "build"
            results = {}
            for part in ("base", "lid"):
                stl = root / (part + ".stl")
                stl.write_text("solid " + part)
                results[part] = slicer.slice_stl(stl, build)

            assert sorted(p.name for p in build.iterdir()) == sorted([
                "base.gcode", "base.gcode.3mf", "base.slicer.log",
                "lid.gcode", "lid.gcode.3mf", "lid.slicer.log", "profiles",
            ]), sorted(p.name for p in build.iterdir())
            for part, result in results.items():
                assert result.gcode == (build / (part + ".gcode")).resolve()
                assert result.gcode_3mf == (build / (part + ".gcode.3mf")).resolve()
                assert "; part " + part in result.gcode.read_text()
                log = (build / (part + ".slicer.log")).read_text()
                assert "slicer message for " + part in log, repr(log)
            assert results["base"].gcode.read_text() != results["lid"].gcode.read_text()
    finally:
        (slicer.find_orcaslicer, slicer._profiles.resolve,
         slicer._profiles.write_flattened, subprocess.run) = saved


